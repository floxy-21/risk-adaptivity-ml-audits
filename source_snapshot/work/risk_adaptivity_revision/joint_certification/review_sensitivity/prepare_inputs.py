"""Extract frozen policy choices for a sensitivity replay; no policy selection.

The complete-panel shared plans are regenerated by the documented raw-source
route. This preparer takes them explicitly, so a journal package does not depend
on private development folders. The output contains only derived study results.
"""
import argparse, ast, csv, hashlib, json
from fractions import Fraction as F
from itertools import combinations
from pathlib import Path

HERE = Path(__file__).resolve().parent
BATCHES = list(combinations(range(1, 6), 2))


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--shared-plans', required=True, type=Path)
    p.add_argument('--ledger', type=Path, default=HERE.parent/'empirical_all_panel_cases.csv')
    p.add_argument('--precision-cases', type=Path, default=HERE.parent/'empirical_precision_all_results/cases.json')
    p.add_argument('--output', type=Path, default=HERE/'frozen_inputs.json')
    a=p.parse_args()
    shared={r['id']:r for r in json.loads(a.shared_plans.read_text())['plans']}
    precision=json.loads(a.precision_cases.read_text())
    with a.ledger.open(newline='') as f: ledger={r['id']:r for r in csv.DictReader(f)}
    assert len(shared)==len(precision)==len(ledger)==1098
    result=[]
    for r in precision:
        s=shared[r['id']]; l=ledger[r['id']]; assert s['id']==l['id']
        mean_pi=[max(F(0),F.from_float(float(v))) for v in s['geometry']['randomized_batch_weights']]
        total=sum(mean_pi); mean_pi=[v/total for v in mean_pi]
        record={k:r[k] for k in ['id','cohort','meter']}
        record['day']=s['day']
        record.update({'batch_widths': r['batch_joint_widths_exact'],
            'adaptive_batch_index': BATCHES.index(tuple(sorted(r['adaptive_queries']))),
            'fixed_batch_index': BATCHES.index(tuple(ast.literal_eval(l['det_batch_queries']))),
            'greedy_batch_index': BATCHES.index(tuple(sorted([int(l['greedy_first']),int(l['greedy_second'])]))),
            'randomized_mean_weights': list(map(str,mean_pi)),
            'randomized_half_precision_weights': r['batch_weights_exact'],
            'lower': r['precision_lower_exact'], 'upper': r['precision_upper_exact'],
            'policy_kind': r['policy_kind']})
        assert abs(float(sum(w*F(v) for w,v in zip(mean_pi,record['batch_widths'])))-float(l['randomized_batch_recorded_expected_J']))<1e-12
        result.append(record)
    sources={name:{'file':path.name,'sha256':hashlib.sha256(path.read_bytes()).hexdigest()} for name,path in [('shared_plans',a.shared_plans),('ledger',a.ledger),('precision_replay',a.precision_cases)]}
    output={'scope':'Frozen derived widths, unchanged choices and mixtures; no raw source data copied.',
        'sources':sources,'batches':[list(q) for q in BATCHES],'cases':result}
    a.output.write_text(json.dumps(output,indent=2)+'\n',encoding='utf8')
    print(json.dumps({'status':'PASS','cases':len(result),'output':str(a.output),'sha256':hashlib.sha256(a.output.read_bytes()).hexdigest()},indent=2))

if __name__=='__main__':main()
